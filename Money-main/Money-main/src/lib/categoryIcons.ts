export function suggestIcon(name: string): string {
  const lower = name.toLowerCase().trim();
  for (const entry of KEYWORD_MAP) {
    if (entry.keywords.some(kw => lower.includes(kw))) return entry.icon;
  }
  return 'folder';
}

